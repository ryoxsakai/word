  ON chapter.list_id = 'crossover-v3' AND chapter.subtitle = '主要単語帳の補完語彙'
WHERE NOT EXISTS (
  SELECT 1 FROM sections existing
  WHERE existing.list_id = 'crossover-v3'
    AND existing.chapter_id = chapter.id
    AND existing.subtitle = source.section_subtitle
);

INSERT INTO words (id, spelling)
SELECT entry.word_id, entry.spelling
FROM _migration_0032_entries entry
WHERE NOT EXISTS (
  SELECT 1 FROM words existing WHERE existing.spelling = entry.spelling COLLATE NOCASE
)
  AND EXISTS (SELECT 1 FROM lists WHERE id = 'crossover-v3');

INSERT INTO senses (word_id, pos, meaning, pronunciation, is_primary, sort_order)
SELECT word.id, NULL, entry.meaning, NULL, 1, 0
FROM _migration_0032_entries entry
JOIN words word ON word.spelling = entry.spelling COLLATE NOCASE
WHERE NOT EXISTS (SELECT 1 FROM senses existing WHERE existing.word_id = word.id);

INSERT INTO tags (word_id, tag_key, tag_value)
SELECT word.id, entry.tag_key, entry.tag_value
FROM _migration_0032_entries entry
JOIN words word ON word.spelling = entry.spelling COLLATE NOCASE
ON CONFLICT(word_id, tag_key) DO UPDATE SET tag_value = excluded.tag_value;

WITH base AS (
  SELECT COALESCE(MAX(no), 0) AS max_no FROM list_items WHERE list_id = 'crossover-v3'
), additions AS (
  SELECT
    word.id AS word_id,
    section.id AS section_id,
    entry.display_order,
    ROW_NUMBER() OVER (ORDER BY entry.display_order) AS offset
  FROM _migration_0032_entries entry
  JOIN words word ON word.spelling = entry.spelling COLLATE NOCASE
  JOIN chapters chapter
    ON chapter.list_id = 'crossover-v3' AND chapter.subtitle = '主要単語帳の補完語彙'
  JOIN sections section
    ON section.list_id = 'crossover-v3'
   AND section.chapter_id = chapter.id
   AND section.subtitle = entry.section_subtitle
  WHERE NOT EXISTS (
    SELECT 1 FROM list_items existing
    WHERE existing.list_id = 'crossover-v3' AND existing.word_id = word.id
  )
)
INSERT INTO list_items (list_id, word_id, no, branch, section_id, label_id)
SELECT 'crossover-v3', additions.word_id, base.max_no + additions.offset, 0, additions.section_id, NULL
FROM additions CROSS JOIN base
ORDER BY additions.display_order;

