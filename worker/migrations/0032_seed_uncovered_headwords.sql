SELECT
  'crossover-v3',
  '',
  source.section_subtitle,
  source.section_subtitle || 'の未カバー語から、独立見出し語として追加した語彙。',
  source.section_order,
  chapter.id
FROM (
  SELECT DISTINCT section_order, section_subtitle
  FROM _migration_0032_entries
) AS source
