import fs from "node:fs";
import { createHash } from "node:crypto";
import { buildIdiomEntries, IDIOM_CHAPTERS, idiomKey } from "../../public/shared/idioms.js";
import { parseWordListItems, stripMarkup } from "../../public/shared/markup.js";

// Reviewed policy: grammar-bearing constructions and representative collocations
// stay with their headword. Other catalogued expressions become idiom entries.
const core = {
  fall: ["fall C"], come: ["come to V", "come to O", "come in different sizes / colors", "come from O", "come across as C"],
  go: ["go on Ving"], turn: ["turn out (to be) C", "turn into O", "turn O into A"],
  look: ["look like O", "look for O", "look in a dictionary", "look in the mirror"],
  lay: [], tell: ["tell A from B", "tell A and B apart"], bring: [], give: [],
  take: ["take A for B", "take O for granted", "take out insurance / a loan"],
  call: ["call on A to V"], set: [], talk: ["talk O into Ving", "talk O out of Ving"],
  get: ["get O to V", "get to O", "get to V", "get on O", "get in / into a car"],
  let: ["let out a cry", "let out a laugh"],
  make: ["be made of O", "be made from O", "be made into O", "make it a rule to V", "make the bed"],
  see: [], watch: [], catch: ["catch a person by the arm"],
  keep: ["keep O from Ving", "keep A from B / Ving", "keep on Ving"],
};
const input = process.argv[2];
if (!input) throw new Error("Usage: node worker/scripts/prepare-idiom-migration.mjs full-words.json");
const { words } = JSON.parse(fs.readFileSync(input, "utf8"));
const entries = buildIdiomEntries(words);
const entryMap = new Map(entries.map(e => [e.key, e]));
const clean = value => stripMarkup(String(value || "")).replace(/～/g, "〜").replace(/\s+/g, " ").trim();
const covered = (phrase, meaning, wordId) => entryMap.get(idiomKey(phrase))?.meanings.some(s => s.meaning === clean(meaning) && s.refs.some(r => r.wordId === wordId));
const changes = [];
for (const word of words.filter(w => w.chapterName === "Chapter 2")) {
  const keeps = new Set((core[word.spelling] || []).map(idiomKey));
  const removedExamples = Object.hasOwn(core, word.spelling) ? word.examples.filter(e => e.type === "phrase" && !e.answer &&
    !keeps.has(idiomKey(e.sentence)) && covered(e.sentence, e.translation, word.id)) : [];
  const items = parseWordListItems(word.relatedWords);
  const removedRelated = items.filter(i => !keeps.has(idiomKey(i.target)) && covered(i.target, i.gloss, word.id));
  if (!removedExamples.length && !removedRelated.length) continue;
  const removed = new Set(removedRelated.map(i => i.index));
  // Keep markup and gloss of every unrelated item, including non-catalog entries.
  const relatedAfter = removedRelated.length ? items.filter(i => !removed.has(i.index))
    .map(i => i.markup + (i.gloss ? ` (${i.gloss})` : "")).join("\n") || null : word.relatedWords;
  changes.push({ wordId: word.id, spelling: word.spelling, relatedBefore: word.relatedWords,
    relatedAfter, removedRelated, removedExamples,
    keptExamples: word.examples.filter(e => e.type === "phrase" && !removedExamples.includes(e)),
    snapshot: { relatedWords: word.relatedWords, examples: word.examples } });
}

const q = value => value == null ? "NULL" : String(value).split(/([\n\r;])/).map(s => s === "\n" ? "char(10)" : s === "\r" ? "char(13)" : s === ";" ? "char(59)" : `'${s.replaceAll("'", "''")}'`).join(" || ");
const idFor = key => `crossover-idiom-${createHash("sha256").update(key).digest("hex").slice(0,24)}`;
const sql = ["-- Generated by scripts/prepare-idiom-migration.mjs. Seed before cleanup; exact-value guards preserve concurrent edits."];
for (const [ci, chapter] of IDIOM_CHAPTERS.entries()) for (const [si, section] of chapter.sections.entries()) {
  sql.push(`INSERT OR IGNORE INTO idiom_sections (list_id, section_key, subtitle, chapter_key, chapter_subtitle, chapter_order, sort_order) SELECT 'crossover-v3', ${q(section.key)}, ${q(section.subtitle)}, ${q(chapter.key)}, ${q(chapter.subtitle)}, ${ci+1}, ${si+1} WHERE EXISTS (SELECT 1 FROM lists WHERE id = 'crossover-v3');`);
}
for (const [index, entry] of entries.entries()) {
  const id = idFor(entry.key);
  sql.push(`INSERT OR IGNORE INTO idioms (id, list_id, phrase, section_key, sort_order) SELECT ${q(id)}, 'crossover-v3', ${q(entry.phrase)}, ${q(entry.sectionKey)}, ${index} WHERE EXISTS (SELECT 1 FROM lists WHERE id = 'crossover-v3');`);
  for (const [si, sense] of entry.meanings.entries()) {
    const sid = `${id}:${si}`;
    sql.push(`INSERT OR IGNORE INTO idiom_senses (id, idiom_id, meaning, sort_order) SELECT ${q(sid)}, ${q(id)}, ${q(sense.meaning)}, ${si} WHERE EXISTS (SELECT 1 FROM idioms WHERE id = ${q(id)});`);
    for (const ref of sense.refs) sql.push(`INSERT OR IGNORE INTO idiom_word_refs (sense_id, word_id, source) SELECT ${q(sid)}, ${q(ref.wordId)}, ${q(ref.source)} WHERE EXISTS (SELECT 1 FROM idiom_senses WHERE id = ${q(sid)}) AND EXISTS (SELECT 1 FROM words WHERE id = ${q(ref.wordId)});`);
  }
}
for (const change of changes) {
  const word = words.find(w => w.id === change.wordId);
  const guard = `EXISTS (SELECT 1 FROM list_items li JOIN sections s ON s.id = li.section_id JOIN chapters c ON c.id = s.chapter_id WHERE li.word_id = ${q(word.id)} AND li.list_id = 'crossover-v3' AND c.id = ${word.chapterId})`;
  // Snapshot is from the current database, not merely the audit download.
  sql.push(`INSERT OR IGNORE INTO idiom_migration_backup (migration_key, word_id, snapshot) SELECT '0038', id, json_object('relatedWords', related_words, 'examples', json((SELECT json_group_array(json_object('id', id, 'sentence', sentence, 'translation', translation, 'type', type, 'sortOrder', sort_order)) FROM examples WHERE word_id = words.id))) FROM words WHERE id = ${q(word.id)} AND ${guard};`);
  const saved = (phrase, meaning) => `EXISTS (SELECT 1 FROM idioms i JOIN idiom_senses s ON s.idiom_id = i.id JOIN idiom_word_refs r ON r.sense_id = s.id WHERE i.list_id = 'crossover-v3' AND i.id = ${q(idFor(idiomKey(phrase)))} AND s.meaning = ${q(clean(meaning))} AND r.word_id = ${q(word.id)})`;
  if (change.removedRelated.length) sql.push(`UPDATE words SET related_words = ${q(change.relatedAfter)}, updated_at = datetime('now') WHERE id = ${q(word.id)} AND related_words IS ${q(change.relatedBefore)} AND ${guard} AND ${change.removedRelated.map(i => saved(i.target, i.gloss)).join(" AND ")};`);
  for (const ex of change.removedExamples) sql.push(`DELETE FROM examples WHERE word_id = ${q(word.id)} AND type = 'phrase' AND sentence = ${q(ex.sentence)} AND translation IS ${q(ex.translation)} AND COALESCE(answer, '') = '' AND ${guard} AND ${saved(ex.sentence, ex.translation)};`);
  if (change.removedExamples.length) sql.push(`UPDATE words SET updated_at = datetime('now') WHERE id = ${q(word.id)} AND ${guard};`);
}
fs.writeFileSync(new URL("../migrations/0038_seed_and_organize_idioms.sql", import.meta.url), sql.join("\n") + "\n");
const audit = { entries: entries.length, meanings: entries.reduce((n,e) => n+e.meanings.length,0), changes };
fs.writeFileSync('/tmp/idiom-organization-audit.json', JSON.stringify(audit, null, 2));
const report = ["# Chapter 2 熟語整理", "", "基本構文・代表的連語は残し、熟語タブで保存を確認できる表現のみ移す。語義・通常の例文・類義語・対義語・他Chapterの掲載は維持する。", "", "| 単語 | 熟語側へ移すフレーズ | 熟語側へ移す関連語 | 単語側に残すフレーズ |", "|---|---|---|---|"];
for (const c of changes) report.push(`| ${c.spelling} | ${c.removedExamples.map(e => e.sentence).join("、").replaceAll("|", "／")} | ${c.removedRelated.map(i => i.target).join("、").replaceAll("|", "／")} | ${c.keptExamples.map(e => e.sentence).join("、").replaceAll("|", "／")} |`);
fs.writeFileSync(new URL("../IDIOM_ORGANIZATION.md", import.meta.url), report.join("\n") + "\n");
console.log(JSON.stringify({ entries: audit.entries, meanings: audit.meanings, words: changes.length,
  movedExamples: changes.reduce((n,c)=>n+c.removedExamples.length,0), movedRelated: changes.reduce((n,c)=>n+c.removedRelated.length,0) }));
